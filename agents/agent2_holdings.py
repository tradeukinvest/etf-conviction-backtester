def _load_from_sqlite(etf: str) -> list[dict] | None:
    """Load holding periods from the permanent SQLite DB, expand to date list."""
    if not HOLDINGS_DB_PATH.exists():
        return None
    try:
        import sqlite3
        conn = sqlite3.connect(HOLDINGS_DB_PATH)
        rows = conn.execute(
            "SELECT stock, start_date, end_date FROM top_holdings WHERE etf=? ORDER BY start_date",
            (etf,)
        ).fetchall()
        conn.close()
        if not rows:
            return None
        # Expand periods back to individual date records for backtest compatibility
        holdings = []
        for stock, start, end in rows:
            holdings.append({
                "date":   start,
                "ticker": stock,
                "weight": None,
                "source": "db",
            })
            if end:
                holdings.append({
                    "date":   end,
                    "ticker": stock,
                    "weight": None,
                    "source": "db",
                })
        return sorted(holdings, key=lambda x: x["date"])
    except Exception:
        return None

