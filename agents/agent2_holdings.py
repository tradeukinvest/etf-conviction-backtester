def _holdings_cache_path(etf: str, freq: str) -> Path:
    return CACHE_DIR / f"holdings_{etf}_{freq}.json"


def _load_holdings_cache(etf: str, freq: str) -> list[dict] | None:
    path = _holdings_cache_path(etf, freq)
    if not path.exists():
        return None
    try:
        with open(path) as f:
            data = json.load(f)
        cached_at = datetime.fromisoformat(data["cached_at"])
        age_days = (datetime.now(timezone.utc) - cached_at).days
        if age_days > HOLDINGS_CACHE_TTL_DAYS:
            return None
        return data["holdings"]
    except Exception:
        return None


def _save_holdings_cache(etf: str, freq: str, holdings: list[dict]):
    CACHE_DIR.mkdir(exist_ok=True)
    path = _holdings_cache_path(etf, freq)
    with open(path, "w") as f:
        json.dump({
            "cached_at": datetime.now(timezone.utc).isoformat(),
            "etf": etf,
            "freq": freq,
            "holdings": holdings,
        }, f, indent=2, default=str)


def _load_cusip_cache() -> dict:
    if CUSIP_CACHE_FILE.exists():
        with open(CUSIP_CACHE_FILE) as f:
            return json.load(f)
    return {}


def _save_cusip_cache(cache: dict):
    CACHE_DIR.mkdir(exist_ok=True)
    with open(CUSIP_CACHE_FILE, "w") as f:
        json.dump(cache, f, indent=2)


def openfigi_lookup(cusip: str, cache: dict) -> str | None:
    """Look up a CUSIP via OpenFIGI free API. Caches results."""
    if not cusip:
        return None
    if cusip in cache:
        return cache[cusip] or None

    try:
        resp = requests.post(
            "https://api.openfigi.com/v3/mapping",
            json=[{"idType": "ID_CUSIP", "idValue": cusip}],
            headers={"Content-Type": "application/json"},
            timeout=10,
        )
        time.sleep(0.4)  # respect ~25 req/10s free tier limit
        if resp.status_code == 200:
            data = resp.json()
            if data and "data" in data[0] and data[0]["data"]:
                ticker = data[0]["data"][0].get("ticker")
                cache[cusip] = ticker
                return ticker
    except Exception:
        pass

    cache[cusip] = None
    return None


def _get_holdings_from_edgar(etf_ticker: str, max_periods: int = 28, freq: str = "quarterly") -> list[dict]:
    """Pull quarterly or annual top holdings from SEC N-PORT filings via edgartools.

    freq="quarterly": one entry per quarter-month (YYYY-MM), up to max_periods
    freq="annual": one entry per year (YYYY), up to max_periods — ~4x fewer EDGAR fetches
    """
    warnings.filterwarnings("ignore")
    try:
        from edgar import Company, set_identity, find_fund
    except ImportError:
        raise ImportError("edgartools not installed. Run: pip install edgartools")

    # SEC EDGAR requires a User-Agent identity
    set_identity("ETF Backtester backtester@example.com")

    cusip_cache = _load_cusip_cache()
    results = []
    target_series_id = None

    # Use find_fund to get the exact series_id for this ETF ticker
    try:
        fc = find_fund(etf_ticker)
        target_series_id = fc.series.series_id
        company = Company(fc.series.fund_company.cik)
    except Exception:
        try:
            company = Company(etf_ticker)
        except Exception as e:
            print(f"  WARNING: Could not find company for {etf_ticker}: {e}")
            return []

    try:
        filings = company.get_filings(form="NPORT-P")
        filing_list = list(filings)
    except Exception as e:
        print(f"  WARNING: Could not fetch N-PORT filings for {etf_ticker}: {e}")
        return []

    print(f"  Found {len(filing_list)} N-PORT filings for {etf_ticker} (series: {target_series_id})")
    cache_dirty = False
    seen_periods: set[str] = set()

    for filing in filing_list:
        if len(results) >= max_periods:
            break
        try:
            filing_date = getattr(filing, "filing_date", None) or getattr(filing, "date", None)
            if filing_date is None:
                continue

            if hasattr(filing_date, "strftime"):
                date_str_ym = filing_date.strftime("%Y-%m")
                date_obj = filing_date
            else:
                date_obj = datetime.strptime(str(filing_date)[:10], "%Y-%m-%d")
                date_str_ym = str(filing_date)[:7]

            # Dedup key: year-only for annual mode, year-month for quarterly
            period_key = date_str_ym[:4] if freq == "annual" else date_str_ym
            if period_key in seen_periods:
                continue

            fund = filing.data_object()

            # Filter to correct fund series when parent entity has multiple series
            if target_series_id:
                try:
                    gi = fund.general_info
                    if gi and gi.series_id and gi.series_id != target_series_id:
                        continue
                except Exception:
                    pass

            investments = getattr(fund, "investments", None)

            if not investments:
                # Fallback to seed
                seed_key = date_str_ym if freq == "quarterly" else date_str_ym
                seed_ticker = SEED_HOLDINGS.get((etf_ticker, seed_key))
                if seed_ticker:
                    seen_periods.add(period_key)
                    results.append({
                        "date": date_obj.strftime("%Y-%m-%d") if hasattr(date_obj, "strftime") else str(date_obj)[:10],
                        "ticker": seed_ticker,
                        "weight": None,
                        "source": "seed",
                    })
                continue

            # Sort by pct_value descending
            sorted_inv = sorted(investments, key=lambda x: (x.pct_value or 0), reverse=True)
            if not sorted_inv:
                continue
            top = sorted_inv[0]
            weight = float(top.pct_value) if top.pct_value else None

            # Resolve ticker: direct field first, then CUSIP lookup, then seed
            ticker = top.ticker if top.ticker else None

            if not ticker and top.cusip:
                ticker = openfigi_lookup(str(top.cusip), cusip_cache)
                cache_dirty = True

            if not ticker:
                ticker = SEED_HOLDINGS.get((etf_ticker, date_str_ym))

            if ticker:
                ticker = str(ticker).strip().upper()
                seen_periods.add(period_key)
                results.append({
                    "date": date_obj.strftime("%Y-%m-%d") if hasattr(date_obj, "strftime") else str(date_obj)[:10],
                    "ticker": ticker,
                    "weight": weight,
                    "source": "edgar",
                })

        except Exception as e:
            print(f"  WARNING: Skipping filing for {etf_ticker}: {e}")
            continue

    if cache_dirty:
        _save_cusip_cache(cusip_cache)

    # Back-fill any missing periods from seed data
    live_yms = {r["date"][:7] for r in results}
    live_years = {r["date"][:4] for r in results}
    for (seed_etf, seed_ym), seed_ticker in SEED_HOLDINGS.items():
        if seed_etf != etf_ticker:
            continue
        if freq == "annual" and seed_ym[:4] in live_years:
            continue
        if freq == "quarterly" and seed_ym in live_yms:
            continue
        results.append({
            "date": f"{seed_ym}-28",
            "ticker": seed_ticker,
            "weight": None,
            "source": "seed-backfill",
        })
        if freq == "annual":
            live_years.add(seed_ym[:4])

    return sorted(results, key=lambda x: x["date"])


def run(etf_list: list[dict], max_periods: int = 28, freq: str = "quarterly") -> dict:
    """
    Fetch top holdings history for each ETF.

    freq="quarterly": one data point per quarter (default, ~28 periods over 7 years)
    freq="annual":    one data point per year (~7 periods), ~4x fewer EDGAR fetches

    Input:  [{"etf": "VOO", "weight": 0.5, "theme": "us equity"}, ...]
    Output: {"VOO": [{"date": "2019-03-31", "ticker": "MSFT", "weight": 4.2}, ...], ...}
    """
    results = {}
    skipped = []
    period_label = "year" if freq == "annual" else "quarter"

    # Split into cached vs needs-fetch (SQLite DB → disk cache → EDGAR)
    to_fetch = []
    for item in etf_list:
        etf = item["etf"]

        # 1. Permanent SQLite DB (pre-built by build_holdings_db.py, no expiry)
        db_data = _load_from_sqlite(etf)
        if db_data:
            print(f"  {etf}: loaded from holdings DB")
            results[etf] = db_data
            continue

        # 2. Disk cache (TTL-based)
        cached = _load_holdings_cache(etf, freq)
        if cached:
            print(f"  {etf}: {len(cached)} {period_label}s from cache")
            results[etf] = cached
            continue

        to_fetch.append(etf)

    if not to_fetch:
        return results

    print(f"  Fetching {len(to_fetch)} ETF(s) from SEC EDGAR in parallel: {', '.join(to_fetch)}")

    def seed_for(etf: str) -> list[dict]:
        entries = [
            {"date": f"{ym}-28", "ticker": tkr, "weight": None, "source": "seed"}
            for (e, ym), tkr in SEED_HOLDINGS.items() if e == etf
        ]
        return sorted(entries, key=lambda x: x["date"])

    def has_full_seed(etf: str) -> bool:
        """True if seed data covers at least 5 years/20 quarters — skip EDGAR."""
        entries = seed_for(etf)
        if freq == "annual":
            years = {e["date"][:4] for e in entries}
            return len(years) >= 5
        return len(entries) >= 20

    def fetch_one(etf: str):
        # Skip EDGAR entirely if seed covers the required periods
        if has_full_seed(etf):
            print(f"  {etf}: using seed data (full coverage, no EDGAR needed)")
            return etf, seed_for(etf)
        holdings = _get_holdings_from_edgar(etf, max_periods, freq)
        if not holdings:
            holdings = seed_for(etf)
        return etf, holdings

    FETCH_TIMEOUT = 90  # seconds per ETF before giving up and using seed

    with ThreadPoolExecutor(max_workers=min(len(to_fetch), 4)) as pool:
        futures = {pool.submit(fetch_one, etf): etf for etf in to_fetch}
        for future in as_completed(futures):
            etf = futures[future]
            try:
                etf, holdings = future.result(timeout=FETCH_TIMEOUT)
            except Exception:
                print(f"  {etf}: EDGAR fetch timed out — using seed data")
                seed_entries = [
                    {"date": f"{ym}-28", "ticker": tkr, "weight": None, "source": "seed"}
                    for (e, ym), tkr in SEED_HOLDINGS.items()
                    if e == etf
                ]
                holdings = sorted(seed_entries, key=lambda x: x["date"]) if seed_entries else []
            if not holdings:
                skipped.append(etf)
                continue
            _save_holdings_cache(etf, freq, holdings)
            results[etf] = holdings
            print(f"  {etf}: {len(holdings)} {period_label}s resolved")

    if skipped:
        print(f"\n  SKIPPED (no data): {', '.join(skipped)}")

    return results
